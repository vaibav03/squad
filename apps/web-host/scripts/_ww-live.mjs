import { chromium } from 'playwright';
const BASE='http://localhost:5190', HUB='http://localhost:8811';
const login = await (await fetch(`${HUB}/v1/auth/dev-login`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ studentId: 's_ana' }) })).json();
const sess = JSON.stringify({ userId: login.student.id, name: 'Ana', token: login.token, avatarUrl: '/avatars/ana.png', live: true });
const b = await chromium.launch();
const c = await b.newContext({ viewport: { width: 1280, height: 800 } });
await c.addInitScript((s) => { localStorage.setItem('squad.session', s); }, sess);
const p = await c.newPage();
p.on('pageerror', (e) => console.log('ERR', String(e).slice(0, 200)));
p.on('console', (m) => ['error','warning','log'].includes(m.type()) && console.log(m.type(), m.text().replace(/st=[^ ]*/,'st=…').slice(0, 300)));
p.on('websocket', (w) => { console.log('ws', w.url().replace(/st=.*/, 'st=…')); w.on('framereceived', (f) => console.log(' <-', String(f.payload).slice(0, 110))); w.on('framesent', (f) => console.log(' ->', String(f.payload).slice(0, 80))); });
await p.goto(`${BASE}/squad/village`);
await p.waitForFunction(() => window.__squadOverlay, null, { timeout: 15000 });
await p.waitForTimeout(2500);
await p.evaluate(() => window.__squadOverlay({ type: 'openCall', agent: 'expert:ch5', callId: 'x' }));
await p.waitForTimeout(3000);
await p.screenshot({ path: '/private/tmp/claude-501/live-call.png' });
await p.getByRole('button', { name: /leave/i }).click();
await p.waitForTimeout(600);
await p.evaluate(() => window.__squadOverlay({ type: 'openQuiz', quizId: 'nope', chapter: 'ch5' }));
await p.waitForTimeout(1500);
await p.screenshot({ path: '/private/tmp/claude-501/live-quiz.png' });
await b.close();
