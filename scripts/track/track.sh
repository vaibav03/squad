#!/usr/bin/env bash
# Regenerates docs/tracking/{BRANCHES,CHANGELOG,AGENTS}.md from git. Deterministic:
# the same git state always yields byte-identical output (no wall-clock values),
# so running it twice in a row changes nothing. macOS bash 3.2 compatible. No secrets.
#
#   scripts/track/track.sh                 # fetch, then regenerate
#   TRACK_NO_FETCH=1 scripts/track/track.sh   # regenerate from the refs already local
#   TRACK_REPO=/path/to/worktree TRACK_OUT=/path/to/docs/tracking  (override targets)
#
# Prints one summary line on stdout: "branches=<n> commits=<m>" (m = commits not on main).
set -euo pipefail
export LC_ALL=C

REPO="${TRACK_REPO:-$(git rev-parse --show-toplevel)}"
OUT="${TRACK_OUT:-$REPO/docs/tracking}"
MAIN="origin/main"
FINAL="origin/integration/final"
TAB=$(printf '\t')
US=$(printf '\037')
g() { git -C "$REPO" "$@"; }

mkdir -p "$OUT"
T="$(mktemp -d "${TMPDIR:-/tmp}/squad-track.XXXXXX")"
trap 'rm -rf "$T"' EXIT

if [ -z "${TRACK_NO_FETCH:-}" ]; then
  g fetch --all --prune --quiet >&2
fi

g rev-parse --verify --quiet "$MAIN" >/dev/null || { echo "no $MAIN" >&2; exit 1; }
BASE_SHA=$(g log "$MAIN" --invert-grep --grep='^track: ' -1 --format=%h)
HAVE_FINAL=0
g rev-parse --verify --quiet "$FINAL" >/dev/null && HAVE_FINAL=1

# ---- remote branches (excluding HEAD) ------------------------------------
g for-each-ref --sort=-committerdate --sort=refname \
  --format='%(refname)' refs/remotes/origin |
  sed 's#^refs/remotes/origin/##' | grep -v '^HEAD$' >"$T/branches" || true

# ---- worktree map: local-branch <TAB> path <TAB> dirty ---------------------
g worktree list --porcelain | awk '
  /^worktree /{p=substr($0,10); br=""}
  /^branch /{br=$2; sub("^refs/heads/","",br); print br "\t" p}
  /^detached/{}' >"$T/wt_raw"
MAIN_WT=$(g worktree list --porcelain | awk '/^worktree /{print substr($0,10); exit}')
PARENT=$(dirname "$MAIN_WT")
: >"$T/wt"
while IFS="$TAB" read -r br path; do
  [ -d "$path" ] || continue
  d=$(git -C "$path" status --short 2>/dev/null | wc -l | tr -d ' ')
  rel="${path#"$PARENT"/}"
  printf '%s\t%s\t%s\n' "$br" "$rel" "$d" >>"$T/wt"
done <"$T/wt_raw"

wtinfo() { # $1 branch -> "path (dirty N)" or "-"
  awk -F'\t' -v b="$1" '$1==b{printf "`%s` (%s)", $2, ($3==0?"clean":$3" dirty"); f=1; exit} END{if(!f) printf "-"}' "$T/wt"
}

fmtage() { # seconds -> compact
  s=$1
  if [ "$s" -le 0 ]; then printf '0m'; return; fi
  d=$((s / 86400)); h=$(((s % 86400) / 3600)); m=$(((s % 3600) / 60))
  if [ "$d" -gt 0 ]; then printf '%dd%dh' "$d" "$h"
  elif [ "$h" -gt 0 ]; then printf '%dh%dm' "$h" "$m"
  else printf '%dm' "$m"; fi
}
esc() { sed -e 's/|/\\|/g' | cut -c1-90; }

NEWEST=$(g for-each-ref --format='%(committerdate:unix)' refs/remotes/origin | sort -rn | head -1)

# ---- BRANCHES.md ------------------------------------------------------------
NB=$(wc -l <"$T/branches" | tr -d ' ')
{
  echo "# Branches"
  echo
  echo "Generated by \`scripts/track/track.sh\` from \`git fetch --all --prune\`. Do not edit by hand."
  echo
  echo "- Base: \`origin/main\` at \`$BASE_SHA\` (tracker commits \`track: ...\` are ignored in behind counts so the tracker does not churn its own output)."
  echo "- **Ahead / behind** are commit counts against \`origin/main\`."
  echo "- **Last commit age** is measured against the newest commit on any remote branch (not wall clock), so this file stays stable between runs."
  echo "- **Merged to final**: \`yes\` = tip is an ancestor of \`$FINAL\`; \`patch\` = every commit has a patch-equivalent there (cherry-picked or rebased); \`n/m\` = only n of m commits are there; \`no\`."
  echo "- **Worktree** is the local checkout of the same-named branch (path relative to \`$PARENT\`) with the number of dirty entries from \`git status --short\`. \`unpushed\` = local commits not on origin."
  echo
  echo "## Remote branches ($NB)"
  echo
  echo "| Branch | Tip | Subject | Author date | Ahead | Behind | Last commit age | Merged to final | Worktree | Unpushed |"
  echo "|---|---|---|---|---:|---:|---|---|---|---:|"
  while IFS= read -r b; do
    [ -n "$b" ] || continue
    ref="origin/$b"
    tip=$(g rev-parse --short "$ref")
    subj=$(g log -1 --format=%s "$ref" | esc)
    adate=$(g log -1 --format=%ad --date=format:'%Y-%m-%d %H:%M %z' "$ref")
    ahead=$(g rev-list --count "$MAIN..$ref")
    behind=$(g rev-list --count --invert-grep --grep='^track: ' "$ref..$MAIN")
    cts=$(g log -1 --format=%ct "$ref")
    age=$(fmtage $((NEWEST - cts)))
    if [ "$ref" = "$MAIN" ]; then merged="(base)"
    elif [ "$HAVE_FINAL" = 0 ]; then merged="n/a"
    elif [ "$ref" = "$FINAL" ]; then merged="(final)"
    elif g merge-base --is-ancestor "$ref" "$FINAL" 2>/dev/null; then merged="yes"
    else
      tot=$(g rev-list --count --no-merges "$MAIN..$ref")
      miss=$(g cherry "$FINAL" "$ref" 2>/dev/null | grep -c '^+' || true)
      if [ "$tot" -eq 0 ]; then merged="yes"
      elif [ "$miss" -eq 0 ]; then merged="patch"
      elif [ "$miss" -eq "$tot" ]; then merged="no"
      else merged="$((tot - miss))/$tot"; fi
    fi
    unp="-"
    if g rev-parse --verify --quiet "refs/heads/$b" >/dev/null; then
      unp=$(g rev-list --count "$ref..refs/heads/$b")
    fi
    printf '| `%s` | `%s` | %s | %s | %s | %s | %s | %s | %s | %s |\n' \
      "$b" "$tip" "$subj" "$adate" "$ahead" "$behind" "$age" "$merged" "$(wtinfo "$b")" "$unp"
  done <"$T/branches"

  # local-only branches (no remote of the same name)
  g for-each-ref --format='%(refname:short)' refs/heads | sort >"$T/local"
  sort "$T/branches" >"$T/remote_sorted"
  comm -23 "$T/local" "$T/remote_sorted" >"$T/localonly"
  echo
  echo "## Local branches not on origin ($(wc -l <"$T/localonly" | tr -d ' '))"
  echo
  echo "Work that exists only on this machine until someone pushes it."
  echo
  echo "| Branch | Tip | Subject | Author date | Ahead of main | Worktree |"
  echo "|---|---|---|---|---:|---|"
  while IFS= read -r b; do
    [ -n "$b" ] || continue
    tip=$(g rev-parse --short "refs/heads/$b")
    subj=$(g log -1 --format=%s "refs/heads/$b" | esc)
    adate=$(g log -1 --format=%ad --date=format:'%Y-%m-%d %H:%M %z' "refs/heads/$b")
    ahead=$(g rev-list --count "$MAIN..refs/heads/$b")
    printf '| `%s` | `%s` | %s | %s | %s | %s |\n' "$b" "$tip" "$subj" "$adate" "$ahead" "$(wtinfo "$b")"
  done <"$T/localonly"
} >"$OUT/BRANCHES.md"

# ---- commit tables (TSV: sha ts author files subject trailers) --------------
# $1 = log args; output TSV on stdout. Trailers come from a second pass.
commit_tsv() {
  # shellcheck disable=SC2086
  g log "$@" --date=format:'%Y-%m-%d %H:%M' --shortstat \
    --format="@${US}%h${US}%ad${US}%an${US}%s" |
    awk -F"$US" -v OFS='\t' '
      /^@/ { if (have) print sha, ts, an, files+0, sub_; have=1; sha=$2; ts=$3; an=$4; sub_=$5; files=0; next }
      /files? changed/ { split($0, a, " "); files=a[1] }
      END { if (have) print sha, ts, an, files+0, sub_ }'
}
trailers_tsv() { # sha <TAB> Co-Authored-By names joined by ';'
  g log "$@" --format="%h${US}%(trailers:key=Co-Authored-By,valueonly,separator=%x3b)" |
    awk -F"$US" -v OFS='\t' '{gsub(/\n/,"",$2); sub(/;$/,"",$2); gsub(/ *<[^>]*>/,"",$2); print $1, $2}'
}

# unmerged set: any commit on a remote branch that is not on origin/main
commit_tsv --remotes=origin --not "$MAIN" >"$T/un_c"
trailers_tsv --remotes=origin --not "$MAIN" >"$T/un_t"
# attribution: each commit goes to the containing branch with the fewest commits ahead
: >"$T/pairs"
while IFS= read -r b; do
  [ "$b" = "main" ] && continue
  n=$(g rev-list --count "$MAIN..origin/$b")
  [ "$n" -gt 0 ] || continue
  g rev-list --abbrev-commit "$MAIN..origin/$b" | awk -v n="$n" -v b="$b" '{print $1 "\t" n "\t" b}' >>"$T/pairs"
done <"$T/branches"
sort -t"$TAB" -k1,1 -k2,2n -k3,3 "$T/pairs" | awk -F'\t' '!s[$1]++ {print $1 "\t" $3}' >"$T/attr"

# join: sha ts author files subject trailers branch
awk -F'\t' -v OFS='\t' '
  FNR==NR && FILENAME==ARGV[1] { c[$1]=$0; next }
  FILENAME==ARGV[2] { t[$1]=$2; next }
  { if ($1 in c) { split(c[$1], f, "\t"); print f[1], f[2], f[3], f[4], f[5], t[$1], $2 } }
' "$T/un_c" "$T/un_t" "$T/attr" | sort -t"$TAB" -k2,2r -k1,1 >"$T/un"

commit_tsv "$MAIN" --invert-grep --grep='^track: ' >"$T/mn_c"
trailers_tsv "$MAIN" --invert-grep --grep='^track: ' >"$T/mn_t"
awk -F'\t' -v OFS='\t' '
  FILENAME==ARGV[1] { t[$1]=$2; next }
  { print $1, $2, $3, $4, $5, t[$1], "main" }
' "$T/mn_t" "$T/mn_c" | sort -t"$TAB" -k2,2r -k1,1 >"$T/mn"

NUN=$(wc -l <"$T/un" | tr -d ' ')
NMN=$(wc -l <"$T/mn" | tr -d ' ')

render() { # $1 = TSV, $2 = group by branch (1/0)
  awk -F'\t' -v byb="$2" '
    function esc(s) { gsub(/\|/, "\\|", s); return s }
    {
      day=substr($2,1,10)
      if (!(day in dseen)) { dseen[day]=1; days[++nd]=day }
      key=day SUBSEP $7
      if (byb && !(key in bseen)) { bseen[key]=1; nb[day]++; bl[day, nb[day]]=$7 }
      n[key]++; line[key, n[key]]=sprintf("- `%s` %s %s (%s, %s file%s)%s", $1, substr($2,12), esc($5), $3, $4, ($4==1?"":"s"), ($6!=""?"  [" $6 "]":""))
      dc[day]++
    }
    END {
      for (i=1;i<=nd;i++) {
        d=days[i]; printf "### %s (%d commit%s)\n\n", d, dc[d], (dc[d]==1?"":"s")
        if (byb) {
          for (j=1;j<=nb[d];j++) { b=bl[d,j]; k=d SUBSEP b; printf "**`%s`** (%d)\n\n", b, n[k]; for (m=1;m<=n[k];m++) print line[k,m]; print "" }
        } else {
          k=d SUBSEP "main"; for (m=1;m<=n[k];m++) print line[k,m]; print ""
        }
      }
    }' "$1"
}

{
  echo "# Changelog"
  echo
  echo "Generated by \`scripts/track/track.sh\` from git. Newest first, grouped by day (author's local date) and by branch. Regenerated from scratch each run; never edited by hand. Times are the author's local time."
  echo
  echo "- A commit that sits on several branches is listed once, under the branch that contains it with the fewest commits ahead of main (so shared base commits go to the earliest workstream branch, not to \`integration/final\`). Rebased or cherry-picked copies have different shas and appear separately."
  echo "- Format: \`sha\` time subject (author, files changed) [Co-Authored-By]."
  echo "- Tracker commits (\`track: ...\`) are omitted."
  echo
  echo "## Commits on remote branches, not on main ($NUN)"
  echo
  if [ "$NUN" -eq 0 ]; then echo "_None: every branch is merged to main._"; echo; else render "$T/un" 1; fi
  echo "## Commits landed on main ($NMN)"
  echo
  render "$T/mn" 0
} >"$OUT/CHANGELOG.md"

# ---- AGENTS.md --------------------------------------------------------------
{
  echo "# Agents and workstreams"
  echo
  echo "Generated by \`scripts/track/track.sh\`. Derived only from commit metadata: branch name prefix, git author, and \`Co-Authored-By\` trailers. Nothing here is hand-maintained."
  echo
  echo "Caveats: the author is the git identity of the machine owner for every commit, and \`Co-Authored-By\` names the model, not an individual agent, so the branch is the only reliable workstream signal. Counts for branches use the same attribution rule as CHANGELOG.md (commits not yet on main)."
  echo
  echo "## By branch prefix"
  echo
  echo "| Prefix | Branches | Commits (not on main) | Files changed (sum) | Co-Authored-By (commits) |"
  echo "|---|---:|---:|---:|---|"
  awk -F'\t' '
    { p=$7; sub("/.*","",p); c[p]++; f[p]+=$4
      if (!(($7) in bs)) { bs[$7]=1; nbr[p]++ }
      split($6, t, ";"); for (i in t) if (t[i]!="") { tk[p SUBSEP t[i]]++; if (!((p SUBSEP t[i]) in ts)) { ts[p SUBSEP t[i]]=1; tl[p]=tl[p] (tl[p]==""?"":SUBSEP) t[i] } } }
    END { for (p in c) { s=""; n=split(tl[p], a, SUBSEP); for (i=1;i<=n;i++) s=s (s==""?"":", ") a[i] " (" tk[p SUBSEP a[i]] ")"; printf "| `%s/` | %d | %d | %d | %s |\n", p, nbr[p], c[p], f[p], (s==""?"-":s) } }' "$T/un" | sort
  echo
  echo "## By workstream branch"
  echo
  echo "| Branch | Commits (not on main) | Files changed (sum) | First commit | Last commit | Authors |"
  echo "|---|---:|---:|---|---|---|"
  awk -F'\t' '
    { b=$7; c[b]++; f[b]+=$4
      if (!(b in last) || $2>last[b]) last[b]=$2
      if (!(b in first) || $2<first[b]) first[b]=$2
      if (index(au[b], "|" $3 "|")==0) au[b]=au[b] "|" $3 "|" }
    END { for (b in c) { a=au[b]; gsub(/\|\|/, ", ", a); gsub(/\|/, "", a); printf "| `%s` | %d | %d | %s | %s | %s |\n", b, c[b], f[b], first[b], last[b], a } }' "$T/un" | sort
  echo
  echo "## Co-Authored-By totals (all commits: not on main plus landed on main)"
  echo
  echo "| Co-Authored-By | Commits |"
  echo "|---|---:|"
  cat "$T/un" "$T/mn" | awk -F'\t' '{ if ($6=="") { none++ } else { n=split($6,t,";"); for (i=1;i<=n;i++) if (t[i]!="") k[t[i]]++ } }
    END { for (x in k) printf "| %s | %d |\n", x, k[x]; if (none) printf "| (no trailer) | %d |\n", none }' | sort
  echo
  echo "## Commits landed on main by area (subject prefix)"
  echo
  echo "| Area | Commits |"
  echo "|---|---:|"
  awk -F'\t' '{ a=$5; i=index(a, ":"); a=(i>0 && i<20)?substr(a,1,i-1):"(other)"; k[a]++ } END { for (x in k) printf "| %s | %d |\n", x, k[x] }' "$T/mn" | sort
  echo
  echo "## Authors (all commits)"
  echo
  echo "| Author | Commits |"
  echo "|---|---:|"
  cat "$T/un" "$T/mn" | awk -F'\t' '{k[$3]++} END{for (x in k) printf "| %s | %d |\n", x, k[x]}' | sort
} >"$OUT/AGENTS.md"

echo "branches=$NB commits=$NUN"
