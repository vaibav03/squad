import type { FullResult, Reporter, TestCase, TestResult } from '@playwright/test/reporter';
import fs from 'node:fs';
import path from 'node:path';
import { LIVE, REPO } from './env';

type Row = {
  title: string;
  status: 'pass' | 'fail' | 'blocked' | 'skipped';
  note: string;
  ms: number;
};
const JOURNEY_TITLES: Record<string, string> = {
  J1: 'Sign in and setup (phone, PDFs, .ics, persona)',
  J2: 'Group chat grounded answer with citation chip',
  J3: 'Private DM privacy',
  J4: 'Quiz round (chat and classroom)',
  J5: 'Ask the council',
  J6: 'Plan my next semester',
  J7: 'Study modes (Feynman, Step Diff, Devil, Debate, Oracle, Rubric, Oral)',
  J8: 'Study scheduling and trip planner (4 students)',
  J9: 'Ledger privacy',
  J10: 'Village (camera, rooms, replay, overlays)',
  J11: 'Media (podcast, explainer, personas voice)',
  J12: 'Mobile, keyboard, horizontal scroll',
  J13: 'Resilience (hub restart, agent offline, 402 recovery)',
  J14: 'Status and doctor',
  J15: 'Security basics',
};

export default class MatrixReporter implements Reporter {
  rows: Row[] = [];
  onTestEnd(test: TestCase, r: TestResult) {
    const blocked = test.annotations.find((a) => a.type === 'blocked');
    const skippedLive = test.annotations.find((a) => a.type === 'skipped-live');
    const notes = test.annotations.filter((a) => a.type === 'note').map((a) => a.description);
    let status: Row['status'];
    if (r.status === 'skipped') status = blocked ? 'blocked' : 'skipped';
    else if (r.status === 'passed') status = 'pass';
    else status = 'fail';
    const note =
      (blocked?.description ? `blocked: ${blocked.description}` : '') +
      (skippedLive?.description ?? '') +
      (status === 'fail' ? (r.error?.message ?? '').split('\n')[0]!.slice(0, 220) : '') +
      (notes.length ? (blocked ? ' | ' : '') + notes.join('; ') : '');
    this.rows.push({ title: test.title, status, note: note.replace(/\|/g, '/'), ms: r.duration });
  }
  onEnd(_: FullResult) {
    const qa = path.join(REPO, 'docs/qa');
    fs.mkdirSync(qa, { recursive: true });
    const jsonPath = path.join(qa, 'e2e-results.json');
    let all: Record<string, { at: string; rows: Row[] }> = {};
    try {
      all = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    } catch {
      /* first run */
    }
    const mode = LIVE ? 'live' : 'demo';
    // keep previous rows for journeys that were not part of this (possibly partial) run
    const prev = all[mode]?.rows ?? [];
    const ran = new Set(this.rows.map((r) => r.title));
    const merged = [...prev.filter((p) => !ran.has(p.title)), ...this.rows];
    all[mode] = { at: new Date().toISOString(), rows: merged };
    fs.writeFileSync(jsonPath, JSON.stringify(all, null, 1));
    fs.writeFileSync(path.join(qa, 'E2E-REPORT.md'), render(all));
  }
}

function jid(t: string) {
  return /^(J\d+)/.exec(t)?.[1] ?? 'J?';
}
function render(all: Record<string, { at: string; rows: Row[] }>): string {
  const out: string[] = [
    '# E2E acceptance report',
    '',
    'Generated by `pnpm e2e` (reporter `e2e/lib/report-reporter.ts`). Do not hand-edit the tables; edit the notes below them. Bugs: `docs/qa/E2E-BUGS.md`. How to run: `docs/qa/E2E-README.md`.',
    '',
  ];
  for (const mode of ['demo', 'live']) {
    const m = all[mode];
    out.push(`## Mode: ${mode}${m ? ` (last run ${m.at})` : ''}`, '');
    if (!m) {
      out.push(
        mode === 'live'
          ? '_Not run (needs `LIVE=1` and a Gemini key with credits)._'
          : '_Not run._',
        '',
      );
      continue;
    }
    out.push(
      '| Journey | Result | pass | fail | blocked | skipped | Evidence |',
      '|---|---|---|---|---|---|---|',
    );
    for (let i = 1; i <= 15; i++) {
      const j = `J${i}`;
      const rows = m.rows.filter((r) => jid(r.title) === j);
      const c = (s: string) => rows.filter((r) => r.status === s).length;
      let res = 'not run';
      if (rows.length) {
        if (c('fail')) res = 'FAIL';
        else if (c('pass') && !c('blocked') && !c('skipped')) res = 'pass';
        else if (c('pass')) res = 'partial';
        else if (c('blocked')) res = 'blocked';
        else res = 'skipped';
      }
      out.push(
        `| ${j} ${JOURNEY_TITLES[j]} | ${res} | ${c('pass')} | ${c('fail')} | ${c('blocked')} | ${c('skipped')} | \`docs/design/shots/e2e/${j.toLowerCase()}-*/\` |`,
      );
    }
    out.push('', '### Step results', '', '| Step | Result | Detail |', '|---|---|---|');
    for (const r of m.rows.sort((a, b) =>
      a.title.localeCompare(b.title, undefined, { numeric: true }),
    ))
      out.push(`| ${r.title} | ${r.status} | ${r.note} |`);
    out.push('');
  }
  return out.join('\n');
}
