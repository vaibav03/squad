import { chromium } from 'playwright';
const CH='/Users/vaibav/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing';
const H='http://localhost:8921', W=process.argv[2]||'http://localhost:5322';
const post=async(p,b,t)=>(await fetch(H+p,{method:'POST',headers:{'content-type':'application/json',...(t?{authorization:'Bearer '+t}:{})},body:JSON.stringify(b)})).json();
const s=await post('/v1/auth/start',{email:`m${Date.now()}@example.com`,name:'Main Repro'});
const v=await post('/v1/auth/verify',{challengeId:s.challengeId,code:s.devCode});
await post('/v1/squads',{name:'summa'},v.token);
const sess={userId:v.user.id,name:v.user.name,token:v.token,live:true};
const b=await chromium.launch({executablePath:CH});
const ctx=await b.newContext({viewport:{width:1280,height:800}});
await ctx.addInitScript(x=>{localStorage.setItem('squad.session',JSON.stringify(x));localStorage.setItem('squad.token',x.token)},sess);
if(W.includes('5322')) await ctx.route(H+'/**',async r=>{const res=await r.fetch().catch(()=>null); if(!res) return r.abort(); r.fulfill({response:res,headers:{...res.headers(),'access-control-allow-origin':W,'access-control-allow-headers':'*'}})});
const p=await ctx.newPage(); p.on('console',m=>['error','warning'].includes(m.type())&&console.log('[c]',m.text().slice(0,200)));
await p.goto(W+'/squad/village'); await p.waitForTimeout(4000);
await p.getByTestId('chat-dock-open').click(); await p.waitForTimeout(6000);
console.log('DOCK:',(await p.getByTestId('chat-dock').innerText()).replace(/\n+/g,' | '));
console.log('send enabled', await p.getByTestId('chat-send').isEnabled().catch(e=>'n/a'));
await p.screenshot({path:'/Users/vaibav/Desktop/squad-demo/floatchat-main-repro.png'});
await p.goto(W+'/squad/chat'); await p.waitForTimeout(6000);
console.log('PAGE:',(await p.evaluate(()=>document.body.innerText)).replace(/\n+/g,' | ').slice(0,300));
await b.close();
