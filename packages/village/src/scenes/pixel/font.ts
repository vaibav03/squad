const cache = new Map<string, boolean[][]>();
function glyph(ch: string): boolean[][] {
  let g = cache.get(ch);
  if (!g) {
    const src = (G[ch.toUpperCase()] ?? G['?'])!;
    g = src.split('/').map((row) => [...row].map((c) => c === '#'));
    cache.set(ch, g);
  }
  return g;
}

export const GLYPH_W = 3;
export const GLYPH_H = 5;

export function textWidth(s: string): number {
  return s.length === 0 ? 0 : s.length * (GLYPH_W + 1) - 1;
}

/** Draw text with the 3x5 font; returns the width drawn. */
export function drawText(r: Raster, x: number, y: number, s: string, ink: Ink): number {
  let cx = x;
  for (const ch of s) {
    const g = glyph(ch);
    for (let j = 0; j < GLYPH_H; j++)
      for (let i = 0; i < GLYPH_W; i++) if (g[j]![i]) r.px(cx + i, y + j, ink);
    cx += GLYPH_W + 1;
  }
  return textWidth(s);
}

export function drawTextCentered(r: Raster, cx: number, y: number, s: string, ink: Ink): void {
  drawText(r, Math.round(cx - textWidth(s) / 2), y, s, ink);
}
